type interval struct {
	first, last rune
}

func inTable(r rune, table []interval) bool {
	lo, hi := 0, len(table)-1
	if r < table[0].first || r > table[hi].last {
		return false
	}
	for lo <= hi {
		mid := (lo + hi) / 2
		switch {
		case r > table[mid].last:
			lo = mid + 1
		case r < table[mid].first:
			hi = mid - 1
		default:
			return true
		}
	}
	return false
}
